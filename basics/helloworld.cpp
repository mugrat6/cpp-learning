// C++'s version of "Hello World" is a bit different.
// still similar, but looks weird

#include <iostream> // <iostream> is standard input/output functions

int main() {
    /* 'std' is C++'s standard library. 
    'cout' i'm assuming is specifically for output
    */
    std::cout << "Hello World!" << std::endl; 
    // 'std::endl' is the same as '\n' in C. its different for the sake of being different.
    std::cout << "bye";
    return 0;
}